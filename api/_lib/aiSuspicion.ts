// 업로더가 제목·설명란·태그·채널명에 스스로 밝힌 표현으로 "AI로 만든 영상"인지 추정한다.
// YouTube의 AI 라벨(containsSyntheticMedia)은 영상 주인만 API로 받을 수 있어서 이 방식을 쓴다 (SPEC F10).
// 스스로 밝히지 않은 영상은 잡지 못하는 추정이므로, 화면에는 "AI 의심"으로 표시한다

export interface AiSuspicionInput {
  title: string;
  channelTitle: string;
  description?: string;
  tags?: string[];
}

// 영문 글자·숫자가 바로 붙어 있지 않을 때만 단어로 본다.
// \b는 한글을 글자로 보지 않아서 "AI커버"를 놓치므로 직접 앞뒤를 확인한다
const START = '(?<![a-z0-9])';
const END = '(?![a-z0-9])';

// 어디에 있든(대소문자 무시) AI 제작을 밝힌 것으로 보는 표현.
// 단어 사이는 \s 대신 스페이스만 본다. 태그를 줄바꿈으로 이어 붙이므로, 서로 다른 태그가 한 표현으로 잡히지 않게 한다
const DISCLOSURE_PATTERNS: RegExp[] = [
  // AI cover, AI-generated, AI music, AI vocals, AI-assisted ...
  new RegExp(
    `${START}ai[ -]?(?:cover|covers|music|songs?|generated|made|vocals?|assisted)${END}`,
    'gi',
  ),
  // made with AI, generated by AI, using AI, with the help of AI ...
  new RegExp(
    `${START}(?:(?:made|created|generated|produced|composed) +(?:with|by|using)|using|with the help of) +ai${END}`,
    'gi',
  ),
  // AI 음악 생성 서비스 이름
  new RegExp(`${START}(?:suno|udio)${END}`, 'gi'),
  // AI 커버, AI음악, AI 노래, AI 생성 ...
  new RegExp(`${START}ai ?(?:커버|음악|노래|생성|작곡|제작)`, 'gi'),
  // AI로 만든, AI로 제작한 ...
  new RegExp(`${START}ai로 ?(?:만든|만들|제작|생성)`, 'gi'),
  // AI를 활용했어요, AI 사용, AI를 이용한 ...
  new RegExp(`${START}ai[를을]? ?(?:활용|사용|이용)`, 'gi'),
];

// 제목과 설명란에 쓰는 규칙: 따로 떨어진 대문자 "AI" (예: "2 Hour AI Trap Mix", "AI 소스를 바탕으로").
// 업로더마다 "AI 소스", "AI 보컬"처럼 쓰는 말이 달라서 표현 목록만으로는 놓친다.
// 대소문자를 구분해서 "Ai", "aim", "MAIN" 같은 경우는 잡지 않는다.
// "AI 추천 알고리즘"처럼 제작과 상관없는 언급도 잡히지만, 배지는 "의심" 표시라 감수한다
const STANDALONE_AI_PATTERN = /(?<![A-Za-z0-9])AI(?![A-Za-z0-9])/g;

// 영어는 부정어가 앞에 온다 (예: "not AI generated", "No AI", "We are not using AI").
// 같은 문장 안에서만 본다. 문장 끝(. ! ? 줄바꿈) 너머의 부정어와 엮이지 않게 한다
const NEGATION_BEFORE_PATTERN = /(?<![a-z])(?:no|not|without|non|never)(?![a-z])[^\n.!?]*$/i;

// 한글은 부정어가 뒤에 온다 (예: "AI가 아닌", "AI 사용 금지", "AI 학습에 사용할 수 없습니다").
// 영어도 뒤에 오는 경우가 있다 (예: "AI tools are not used", "AI training is prohibited")
const NEGATION_AFTER_PATTERN =
  /^[^\n.!?]*?(?:않|안 ?[함했해]|아[니닌님닙]|없|금지|(?<![a-z])(?:not|never|prohibited|forbidden|banned)(?![a-z]))/i;

// 표현 앞뒤로 이만큼만 본다. 너무 멀리 보면 상관없는 부정어까지 잡힌다
const NEGATION_RANGE = 25;

// 부정어 없이 쓰인 표현이 하나라도 있으면 true
function hasDisclosure(text: string, pattern: RegExp): boolean {
  for (const match of text.matchAll(pattern)) {
    const end = match.index + match[0].length;
    const before = text.slice(Math.max(0, match.index - NEGATION_RANGE), match.index);
    const after = text.slice(end, end + NEGATION_RANGE);
    if (!NEGATION_BEFORE_PATTERN.test(before) && !NEGATION_AFTER_PATTERN.test(after)) return true;
  }
  return false;
}

export function isAiSuspected({
  title,
  channelTitle,
  description = '',
  tags = [],
}: AiSuspicionInput): boolean {
  if ([title, description].some((text) => hasDisclosure(text, STANDALONE_AI_PATTERN))) return true;

  // 태그는 따로따로 확인해야 하므로 줄바꿈으로 이어 붙인다 (이어진 태그끼리 한 표현으로 잡히지 않게)
  const texts = [title, channelTitle, description, tags.join('\n')];
  return texts.some((text) => DISCLOSURE_PATTERNS.some((pattern) => hasDisclosure(text, pattern)));
}
