import { describe, expect, it } from 'vitest';
import { isAiSuspected } from './aiSuspicion.js';

// 제목만 바꿔 가며 확인할 때 쓴다
function titleOnly(title: string) {
  return isAiSuspected({ title, channelTitle: '채널' });
}

describe('isAiSuspected', () => {
  describe('제목', () => {
    // 실제 "AI music playlist" 검색 결과에 있던 제목들
    it.each([
      'SOUNDYXI Club Bangers | 2 Hour AI Trap & Pop Rap Mix | Night',
      '80s 90s ROMANTIC POWER BALLADS (AI COVER) 🎤 Timeless Love S',
      'Afrikaanse AI Musiek Mix #KI',
      'COLLIDE PLAYLIST - Voxmix (Rock Cover AI Version)',
      'MUSIC TOP 💖HEART💖 I AI COVER I SWEET HEART [ PLAYLIST]',
    ])('따로 떨어진 대문자 AI가 있으면 의심한다: %s', (title) => {
      expect(titleOnly(title)).toBe(true);
    });

    it.each([
      'AI가 만든 감성 플레이리스트',
      '[AI커버] 발라드 모음',
      'Chill ai music for study',
      'lofi ai-generated beats',
    ])('한글이 붙은 AI나 AI 제작 표현이 있으면 의심한다: %s', (title) => {
      expect(titleOnly(title)).toBe(true);
    });

    // 실제 검색 결과의 일반 영상 제목과, 글자 속에 ai가 들어 있는 제목들
    it.each([
      '운전할 때 무조건 듣는 드라이브 노래 🚗💨 | 신나는 Drive Playlist',
      'Relaxing Vibes - A1 Songs | (Reggae Version)',
      'Best Chill Vibes Playlist 2026 💗🎧 | Top Spotifiy Love Song',
      'RAIN 노래 모음 | MAIN THEME',
      'Ai Higuchi 히구치 아이 playlist',
      'Thai pop hits to aim higher',
    ])('AI 제작 표현이 없으면 의심하지 않는다: %s', (title) => {
      expect(titleOnly(title)).toBe(false);
    });

    it('No AI처럼 부정하는 표현은 의심하지 않는다', () => {
      expect(titleOnly('Real Band Music, No AI | Indie Playlist')).toBe(false);
      expect(titleOnly('Not AI generated - 100% human playlist')).toBe(false);
    });
  });

  describe('설명란·태그·채널명', () => {
    it('설명란에 AI로 만들었다고 밝혔으면 의심한다', () => {
      const base = { title: 'Chill Playlist', channelTitle: 'Chill Room' };

      expect(isAiSuspected({ ...base, description: 'All songs were made with Suno.' })).toBe(true);
      expect(isAiSuspected({ ...base, description: 'This music is generated by AI' })).toBe(true);
      expect(isAiSuspected({ ...base, description: '이 영상의 음악은 AI로 만든 곡입니다.' })).toBe(
        true,
      );
    });

    it('설명란에서 부정하거나, 소문자 ai 단어만 있으면 의심하지 않는다', () => {
      const base = { title: 'Chill Playlist', channelTitle: 'Chill Room' };

      expect(isAiSuspected({ ...base, description: 'These songs are not AI generated.' })).toBe(
        false,
      );
      expect(isAiSuspected({ ...base, description: 'Made without AI. Real musicians.' })).toBe(
        false,
      );
      // 따로 떨어진 대문자 AI라도 뒤에 영어 부정어가 오면 잡지 않는다
      expect(isAiSuspected({ ...base, description: 'Follow us! AI tools are not used.' })).toBe(
        false,
      );
      expect(isAiSuspected({ ...base, description: '오디오 audio 품질 최고' })).toBe(false);
    });

    // 실제 영상(vsUns_XFcc0) 설명란. YouTube의 AI 라벨은 API로 받을 수 없지만 업로더가 설명란에도 밝혀 두었다
    it('설명란에 AI를 활용했다고 밝혔으면 의심한다', () => {
      const base = { title: 'Chill Playlist', channelTitle: 'HanGroove' };
      const description = [
        '💜 한그루브(HanGroove)가 기획하고 만든 오리지널 음악입니다.',
        '제작 과정에 AI를 활용했어요. 좋게 들어주셔서 감사해요 🙏',
        '무단 복제·배포·재편집은 삼가주세요.',
      ].join('\n');

      expect(isAiSuspected({ ...base, description })).toBe(true);
      expect(isAiSuspected({ ...base, description: 'AI 사용 음원입니다' })).toBe(true);
      expect(isAiSuspected({ ...base, description: 'Produced using AI tools.' })).toBe(true);
      expect(isAiSuspected({ ...base, description: 'AI-assisted lofi beats' })).toBe(true);
    });

    // 실제 영상(-gFdfAFS2iY) 설명란. "AI 소스"처럼 표현 목록에 없는 말도 따로 떨어진 대문자 AI로 잡는다
    it('설명란에 따로 떨어진 대문자 AI가 있으면 의심한다', () => {
      const description = [
        '*본 채널의 모든 곡은 AI 소스를 바탕으로 직접 기획 및 제작하고,',
        '테마에 맞는 큐레이션과 오디오 믹싱을 더해 완성한 모카냥의 자체제작 콘텐츠입니다.',
      ].join('\n');

      expect(isAiSuspected({ title: 'Chill Playlist', channelTitle: '모카냥', description })).toBe(
        true,
      );
      expect(
        isAiSuspected({
          title: 'Chill Playlist',
          channelTitle: '채널',
          description: 'AI 보컬 버전',
        }),
      ).toBe(true);
    });

    it.each([
      'AI를 사용하지 않았어요.',
      '이 곡은 AI 음악 아님!',
      'AI 사용 금지',
      'AI를 이용한 편집 없이 직접 연주했습니다',
      'We are not using AI.',
      'AI 아닙니다. 직접 부른 노래예요',
      'AI가 아닌 사람이 직접 부른 노래',
      '본 영상의 AI 학습을 금지합니다',
      'AI 학습에 사용할 수 없습니다',
      'AI training is prohibited.',
    ])('부정하는 표현이면 의심하지 않는다: %s', (description) => {
      expect(isAiSuspected({ title: 'Chill Playlist', channelTitle: '채널', description })).toBe(
        false,
      );
    });

    it('부정어가 다음 문장에 있으면 앞 문장의 표현과 엮지 않는다', () => {
      const description = 'AI를 활용했어요. 무단 복제는 하지 않기로 해요.';

      expect(isAiSuspected({ title: 'Chill Playlist', channelTitle: '채널', description })).toBe(
        true,
      );
    });

    it('태그에 AI 제작 표현이 있으면 의심한다', () => {
      expect(
        isAiSuspected({ title: 'Playlist', channelTitle: '채널', tags: ['lofi', 'suno ai'] }),
      ).toBe(true);
    });

    it('서로 다른 태그가 이어져서 한 표현으로 잡히지 않는다', () => {
      expect(
        isAiSuspected({ title: 'Playlist', channelTitle: '채널', tags: ['openai', 'music'] }),
      ).toBe(false);
      expect(
        isAiSuspected({ title: 'Playlist', channelTitle: '채널', tags: ['ai', 'music'] }),
      ).toBe(false);
    });

    it('채널명에 AI 제작 표현이 있으면 의심한다', () => {
      expect(isAiSuspected({ title: 'Playlist', channelTitle: 'AI Music Lab' })).toBe(true);
    });
  });
});
